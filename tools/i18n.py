#!/usr/bin/env python3
"""Herdr app layouts in other languages, built from translation catalogs.

  i18n.py fetch                     download the pinned herdr-app source into .cache/
  i18n.py extract                   refresh source/strings.json from that source
  i18n.py new <locale> --name N --title T   start a catalog for a new language
  i18n.py check [locale ...]        coverage, stale entries and broken translations
  i18n.py build [locale ...]        write <locale>/ for every (or the given) catalog
  i18n.py install <locale> [--home DIR] [--keys]   copy a build into a Herdr app home
  i18n.py upgrade <tag>             pin another herdr-app release

Every command takes --upstream DIR to use a herdr-app checkout instead of the cache.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request

sys.path.insert(0, str(Path(__file__).resolve().parent))
import jslex  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / 'locales'
SOURCE = ROOT / 'source'
MARK = '// Generated by herdr-i18n'
CODE = re.compile(r'^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$')


def config():
    return json.loads((ROOT / 'upstream.json').read_text())


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')


# ---- upstream source

def github(path):
    request = urllib.request.Request('https://api.github.com/' + path,
                                     headers={'Accept': 'application/vnd.github+json', 'User-Agent': 'herdr-i18n'})
    if os.environ.get('GITHUB_TOKEN'):
        request.add_header('Authorization', 'Bearer ' + os.environ['GITHUB_TOKEN'])
    return urllib.request.urlopen(request, timeout=300)


def upstream(args):
    """The herdr-app source tree to build from: --upstream, or the pinned release in .cache/."""
    if args.upstream:
        return Path(args.upstream).resolve()
    cfg = config()
    target = ROOT / '.cache' / f"herdr-app-{cfg['tag']}"
    if not target.exists():
        fetch(cfg, target)
    return target


def fetch(cfg, target):
    print(f"Downloading {cfg['repository']} {cfg['tag']}…", file=sys.stderr)
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=target.parent) as tmp:
        archive = Path(tmp) / 'src.tar.gz'
        with github(f"repos/{cfg['repository']}/tarball/{cfg['tag']}") as response, archive.open('wb') as out:
            shutil.copyfileobj(response, out)
        with tarfile.open(archive) as tar:
            top = {m.name.split('/')[0] for m in tar.getmembers()}
            if len(top) != 1 or not top.pop().endswith('-' + cfg['commit'][:7]):
                raise SystemExit(f"the {cfg['tag']} archive is not commit {cfg['commit']}")
            tar.extractall(tmp, filter='data')
        (folder,) = [p for p in Path(tmp).iterdir() if p.is_dir()]
        folder.rename(target)


def sources(up):
    """(mod name, its upstream folder, its .js files) for every mod a layout translates."""
    cfg = config()
    for group, names in (('mods', cfg['mods']), ('frame', cfg['frames'])):
        for name in names:
            folder = up / 'defaults' / group / name
            if not folder.is_dir():
                raise SystemExit(f'{folder} is missing: update the mod lists in upstream.json')
            yield name, folder, sorted(folder.glob('*.js'))


# ---- the text in the source

def texts(src):
    """('literal', value, token) and ('template', body, token) for each string in src.
    A template's nested strings follow it, so a translation can cover either."""
    def walk(tokens):
        for t in tokens:
            if t.kind == 'string':
                yield 'literal', jslex.string_value(src[t.start:t.end]), t
            elif t.kind == 'template':
                yield 'template', src[t.start + 1:t.end - 1], t
                yield from walk(t.children)
    return walk(jslex.tokenize(src))


def mod_texts(name, folder, scripts):
    """(file, line, kind, text, token) for every string in one mod, its mod.json title included."""
    title = json.loads((folder / 'mod.json').read_text()).get('title')
    if title:
        yield f'{name}/mod.json', 1, 'literal', title, None
    for script in scripts:
        src = script.read_text()
        for kind, text, token in texts(src):
            yield f'{name}/{script.name}', src.count('\n', 0, token.start) + 1, kind, text, token


def looks_like_text(kind, text):
    """Whether a string is probably shown to people (the rest is ids, git flags, code)."""
    if kind == 'template':
        spaced = re.sub(r'\$\{[\s\S]*?\}', ' ', text)
        # "${n} agents" is text; "row-${id}" and "mods/${icon}.svg" are not.
        if '${' in text and re.search(r'(^|\s)[^\W\d_]{2,}[.…:;,!?]*(\s|$)', spaced) and not re.search(r'[\w-]/|/[\w.]', spaced):
            return True
        text = re.sub(r'\$\{[\s\S]*?\}', '', text)
    if not re.search(r'[^\W\d_]{2}', text) or text.lstrip().startswith(('-', '$', '#', '[', 'x-')):
        return False
    if ' ' in text.strip():
        return True
    return bool(re.match(r'^\W*[A-Z][a-z]', text)) or bool(re.search(r'[^\x00-\x7f]', text))


def extract(args):
    up = upstream(args)
    rules = json.loads((SOURCE / 'rules.json').read_text())
    ignore = set(rules['ignore'])
    include = {(r['file'], r['text']) if isinstance(r, dict) else ('*', r) for r in rules['include']}
    found = {'literal': {}, 'template': {}}
    scoped = {}
    for name, folder, scripts in sources(up):
        covered = []  # (file, span) of templates already listed: their nested strings are part of them
        for file, line, kind, text, token in mod_texts(name, folder, scripts):
            inside = token and any(f == file and a <= token.start < b for f, (a, b) in covered)
            if inside or text in ignore:
                continue
            if ('*', text) in include or (file, text) in include or looks_like_text(kind, text):
                found[kind].setdefault(text, []).append(f'{file}:{line}')
                if kind == 'template':
                    covered.append((file, (token.start, token.end)))
                elif (file, text) in include:
                    scoped.setdefault(file, set()).add(text)
    cfg = config()
    data = {'upstream': {'tag': cfg['tag'], 'commit': cfg['commit']},
            'literals': dict(sorted(found['literal'].items())),
            'templates': dict(sorted(found['template'].items())),
            # Elsewhere these words are ids, so they are translated only in these files.
            'per_file': {file: sorted(texts) for file, texts in sorted(scoped.items())}}
    old = json.loads((SOURCE / 'strings.json').read_text()) if (SOURCE / 'strings.json').exists() else None
    write_json(SOURCE / 'strings.json', data)
    print(f"source/strings.json: {len(data['literals'])} strings, {len(data['templates'])} templates")
    if old:
        for key in ('literals', 'templates'):
            added = sorted(set(data[key]) - set(old[key]))
            gone = sorted(set(old[key]) - set(data[key]))
            for text in added:
                print('  + ' + json.dumps(text, ensure_ascii=False))
            for text in gone:
                print('  - ' + json.dumps(text, ensure_ascii=False))


# ---- catalogs

def catalogs(names):
    if not names:
        names = sorted(p.stem for p in LOCALES.glob('*.json'))
    out = []
    for name in names:
        path = LOCALES / f'{name}.json'
        if not CODE.match(name):
            raise SystemExit(f'{name} is not a BCP 47 language code')
        if not path.exists():
            raise SystemExit(f'no catalog {path.relative_to(ROOT)}')
        out.append((name, json.loads(path.read_text())))
    return out


def lookup(catalog, file):
    """The translation for one kind of text in one file, or None to keep it."""
    local = catalog.get('per_file', {}).get(file, {})

    def find(kind, text):
        if text in local:
            return local[text] or None  # null keeps the English here; "" isn't translated yet
        return catalog[kind + 's'].get(text) or None
    return find


def problems(catalog):
    """Translations that would break the mods: a template must keep exactly its ${...}."""
    errors = [f'needs "{k}"' for k in ('locale', 'name', 'title', 'literals', 'templates') if not catalog.get(k)]
    if errors:
        return errors
    tables = [('templates', catalog['templates'])] + [
        (f'per_file[{f}]', {k: v for k, v in t.items() if '${' in k}) for f, t in catalog.get('per_file', {}).items()]
    for where, table in tables:
        for before, after in table.items():
            if after is None or after == '':
                continue
            try:
                if sorted(jslex.holes(before)) != sorted(jslex.holes(after)):
                    errors.append(f'{where}: {before!r} must keep the same ${{...}} expressions')
            except jslex.LexError as e:
                errors.append(f'{where}: {after!r} is not a template body ({e})')
    for before, after in catalog['literals'].items():
        if not isinstance(after, str):
            errors.append(f'literals: {before!r} needs a string')
    return errors


def covered(catalog, kind, text, where):
    """Whether a text has a translation where it appears (a per_file null keeps the English on purpose)."""
    local = catalog.get('per_file', {}).get(where.rsplit(':', 1)[0], {})
    return local[text] != '' if text in local else bool(catalog[kind + 's'].get(text))


def check(args):
    up = upstream(args)
    strings = json.loads((SOURCE / 'strings.json').read_text())
    present, by_file = {'literal': set(), 'template': set()}, {}
    for name, folder, scripts in sources(up):
        for file, line, kind, text, token in mod_texts(name, folder, scripts):
            present[kind].add(text)
            by_file.setdefault(file, set()).add(text)
    failed = False
    for code, catalog in catalogs(args.locales):
        errors = problems(catalog)
        missing = [(k, text) for k in ('literal', 'template') for text, where in strings[k + 's'].items()
                   if not all(covered(catalog, k, text, w) for w in where)]
        stale = [text for k in ('literal', 'template') for text in catalog[k + 's'] if text not in present[k]]
        stale += [f'{file}: {text}' for file, table in catalog.get('per_file', {}).items()
                  for text in table if text not in by_file.get(file, ())]
        total = len(strings['literals']) + len(strings['templates'])
        done = total - len(missing)
        print(f'{code}: {done}/{total} translated ({100 * done / max(total, 1):.1f}%), '
              f'{len(missing)} missing, {len(stale)} stale, {len(errors)} errors')
        for e in errors:
            print('  error: ' + e)
        if args.verbose:
            for k, text in missing:
                print(f"  missing {k}: {json.dumps(text, ensure_ascii=False)}  ({', '.join(strings[k + 's'][text][:3])})")
            for text in stale:
                print('  stale: ' + json.dumps(text, ensure_ascii=False))
        failed |= bool(errors) or (args.strict and bool(missing or stale))
    if failed:
        raise SystemExit(1)


def new(args):
    if not CODE.match(args.locale):
        raise SystemExit('use a BCP 47 code such as ja, ko, fr, zh-TW or pt-BR')
    path = LOCALES / f'{args.locale}.json'
    if path.exists():
        raise SystemExit(f'{path.relative_to(ROOT)} already exists')
    strings = json.loads((SOURCE / 'strings.json').read_text())
    only_there = {text for texts in strings['per_file'].values() for text in texts}
    write_json(path, {
        'locale': args.locale, 'name': args.name, 'title': args.title, 'maintainers': [],
        'literals': {text: '' for text in strings['literals'] if text not in only_there},
        'templates': {text: '' for text in strings['templates']},
        'per_file': {file: {text: '' for text in texts} for file, texts in strings['per_file'].items()},
    })
    print(f'Wrote {path.relative_to(ROOT)}: fill in the empty strings, then run check and build.')


# ---- building a layout

def translate(src, find, risky):
    """src with every catalogued text translated, and "herdr" imported through ./api.js."""
    edits = []
    translated = 0

    def walk(tokens):
        nonlocal translated
        for t in tokens:
            if t.kind == 'string':
                value = jslex.string_value(src[t.start:t.end])
                if value == 'herdr' and re.search(r'\b(from|import)\s*\(?\s*$', src[max(0, t.start - 12):t.start]):
                    edits.append((t.start, t.end, '"./api.js"'))
                    continue
                after = find('literal', value)
                if after is not None:
                    # Text the code compares is a value, not something people read.
                    if re.search(r'(===?|!==?|\bcase)\s*$', src[max(0, t.start - 8):t.start]) or \
                            re.match(r'\s*(===?|!==?)', src[t.end:t.end + 4]):
                        risky.append(value)
                        continue
                    translated += 1
                    edits.append((t.start, t.end, json.dumps(after, ensure_ascii=False)))
            elif t.kind == 'template':
                after = find('template', src[t.start + 1:t.end - 1])
                if after is not None:
                    translated += 1
                    edits.append((t.start, t.end, '`' + after + '`'))
                else:
                    walk(t.children)
    walk(jslex.tokenize(src))
    for start, end, text in reversed(edits):
        src = src[:start] + text + src[end:]
    return src, translated


def apply_patches(src, file, cfg, layout, title, applied=None):
    """The small code changes a layout needs, such as naming itself in Settings."""
    for i, patch in enumerate(cfg['patches']):
        if patch['file'] == file:
            if patch['find'] not in src:
                raise SystemExit(f"patch for {file} no longer applies: {patch['find']!r}")
            src = src.replace(patch['find'], patch['replace'].replace('{layout}', layout).replace(
                '{title}', json.dumps(title, ensure_ascii=False)), 1)
            if applied is not None:
                applied.add(i)
    return src


def keys_section(bindings, prefix, cfg):
    """The bindings that open Herdr's own screens, pointed at the translated ones."""
    mods = set(cfg['mods']) | set(cfg['frames'])
    out = {}
    for key, action in bindings.items():
        if isinstance(action, dict):
            name, given = action.get('command'), action.get('args') or {}
            if name == 'mod.open' and set(given) == {'name'}:
                arg = given['name']
            elif given:
                continue  # e.g. Settings at a section: mod.open can't pass that on
            else:
                arg = None
        else:
            name, _, arg = action.partition(':')
            arg = arg or None
        if name == 'mod.open' and arg in mods:
            out[key] = f'mod.open:{prefix}{arg}'
        elif name in cfg['keys'] and arg is None:
            out[key] = f"mod.open:{prefix}{cfg['keys'][name]}"
    return out


def build(args):
    up = upstream(args)
    cfg = config()
    names = cfg['mods'] + cfg['frames']
    for code, catalog in catalogs(args.locales):
        errors = problems(catalog)
        if errors:
            raise SystemExit(f'{code}: ' + '\n'.join(errors))
        layout = code.lower()
        prefix = layout + '-'
        out = ROOT / layout
        if out.exists():
            shutil.rmtree(out)
        risky, translated, patched = [], 0, set()
        shim = (ROOT / 'tools' / 'shim.js').read_text().replace('__CONFIG__', json.dumps(
            {'prefix': prefix, 'mods': names, 'screens': cfg['screens']}, ensure_ascii=False))
        for name, folder, scripts in sources(up):
            destination = out / 'mods' / (prefix + name)
            destination.mkdir(parents=True)
            group = 'frame' if name in cfg['frames'] else 'mods'
            for script in scripts:
                file = f'{name}/{script.name}'
                src = script.read_text()
                src = apply_patches(src, file, cfg, layout, catalog['title'], patched)
                src, count = translate(src, lookup(catalog, file), risky)
                translated += count
                header = f"{MARK} from herdr-app {cfg['tag']} defaults/{group}/{file} ({code}).\n"
                (destination / script.name).write_text(header + src)
            (destination / 'api.js').write_text(shim)
            hint = json.loads((folder / 'mod.json').read_text())
            if hint.get('title'):
                hint['title'] = catalog['literals'].get(hint['title']) or hint['title']
            hint['place'] = 'none'  # the layout places them; no copy docks by itself
            if name in cfg['screens'] and 'overlay' not in hint:
                hint['overlay'] = cfg['screens'][name]
            write_json(destination / 'mod.json', hint)
        if len(patched) != len(cfg['patches']):
            raise SystemExit('a patch in upstream.json matched no file')

        tree = json.loads((up / 'defaults' / 'layouts' / 'main.json').read_text())

        def localize(node):
            if isinstance(node, dict):
                if node.get('mod') in names:
                    node['mod'] = prefix + node['mod']
                for value in node.values():
                    localize(value)
            elif isinstance(node, list):
                for value in node:
                    localize(value)
        localize(tree)
        tree['terminal_menu'] = prefix + 'menu'
        (out / 'layouts').mkdir()
        write_json(out / 'layouts' / f'{layout}.json', tree)
        for keys in ('keys.json', 'keys.macos.json'):
            shipped = json.loads((up / 'defaults' / keys).read_text())
            write_json(out / keys, {f'layout:{layout}': keys_section(shipped['global'], prefix, cfg)})
        shutil.copy(up / 'LICENSE', out / 'LICENSE')
        write_json(out / 'build.json', {'locale': code, 'layout': layout, 'repository': cfg['repository'],
                                        'tag': cfg['tag'], 'commit': cfg['commit'], 'translated': translated})
        recipe = (ROOT / 'tools' / 'RECIPE.md').read_text()
        for k, v in {'title': catalog['title'], 'name': catalog['name'], 'locale': code, 'layout': layout,
                     'prefix': prefix, 'tag': cfg['tag'], 'mods': ', '.join(f'`{prefix}{n}`' for n in names)}.items():
            recipe = recipe.replace('{' + k + '}', v)
        (out / 'RECIPE.md').write_text(recipe)
        preview = LOCALES / f'{code}.png'
        if preview.exists():
            shutil.copy(preview, out / 'preview.png')
        print(f'{code}: {layout}/ with {len(names)} mods, {translated} texts translated')
        for value in sorted(set(risky)):
            print(f'  kept in English where the code compares it: {json.dumps(value, ensure_ascii=False)}')


# ---- installing into a Herdr app home

def owner(folder):
    """The locale whose build wrote this mod folder, or None."""
    main = folder / 'main.js'
    first = main.read_text().split('\n', 1)[0] if main.exists() else ''
    m = re.match(re.escape(MARK) + r' .*\((\S+)\)\.$', first)
    return m and m.group(1)


def install(args):
    layout = args.locale.lower()
    build_dir = ROOT / layout
    if not (build_dir / 'build.json').exists():
        raise SystemExit(f'{layout}/ is not built: run build {args.locale} first')
    code = json.loads((build_dir / 'build.json').read_text())['locale']
    home = Path(args.home or os.environ.get('HERDR_APP_HOME') or Path.home() / '.config' / 'herdr-app').expanduser()
    if not (home / 'layouts').is_dir():
        raise SystemExit(f'{home} is not a Herdr app home: open Herdr once, or pass --home')
    prefix = layout + '-'
    shipped = sorted(p.name for p in (build_dir / 'mods').iterdir())
    for name in shipped:
        if (home / 'mods' / name).exists() and owner(home / 'mods' / name) != code:
            raise SystemExit(f"{home / 'mods' / name} is not from this build; move it away first")
    target = home / 'layouts' / f'{layout}.json'
    if target.exists() and json.loads(target.read_text()).get('terminal_menu') != prefix + 'menu':
        raise SystemExit(f'{target} is not from herdr-i18n; move it away first')
    for folder in sorted((home / 'mods').glob(prefix + '*')):
        if folder.name not in shipped and owner(folder) == code:
            shutil.rmtree(folder)  # an earlier build's mod this one no longer has
    for name in shipped:
        temporary = home / 'mods' / f'.{name}.new'
        shutil.rmtree(temporary, ignore_errors=True)
        shutil.copytree(build_dir / 'mods' / name, temporary)
        shutil.rmtree(home / 'mods' / name, ignore_errors=True)
        temporary.rename(home / 'mods' / name)
    shutil.copy(build_dir / 'layouts' / f'{layout}.json', target)
    print(f'Installed {len(shipped)} mods and layouts/{layout}.json into {home}')
    built = json.loads((build_dir / 'build.json').read_text())['tag']
    try:
        running = subprocess.run(['herdr-app', '--version'], capture_output=True, text=True).stdout.split()[-1]
    except (OSError, IndexError):
        running = None
    if running and 'v' + running != built:
        print(f'This build is for herdr-app {built}, and you have {running}. Update whichever is older.')
    if args.keys:
        keys = home / 'keys.json'
        if not keys.exists():
            raise SystemExit(f'{keys} is missing; open Herdr once first')
        mine = json.loads(keys.read_text())
        mine[f'layout:{layout}'] = keys_section(mine.get('global', {}), prefix, config())
        write_json(keys, mine)
        print(f'Added a layout:{layout} section to {keys}. Herdr now treats keys.json as yours '
              'and stops adding new default shortcuts to it.')
    print(f'Switch to it in Settings > Look, or: herdr-app do layout.switch \'{{"name":"{layout}"}}\'')


# ---- moving to another herdr-app release

def upgrade(args):
    cfg = config()
    with github(f"repos/{cfg['repository']}/commits/{args.tag}") as response:
        commit = json.load(response)['sha']
    cfg['tag'], cfg['commit'] = args.tag, commit
    write_json(ROOT / 'upstream.json', cfg)
    print(f'Pinned {args.tag} ({commit})')
    up = upstream(args)
    shipped = {p.name for p in (up / 'defaults' / 'mods').iterdir() if p.is_dir()}
    unknown = shipped - set(cfg['mods']) - {'terminals-bar', 'terminals-pane', 'toast', 'win98'}
    if unknown:
        print('New shipped mods, not translated yet: ' + ', '.join(sorted(unknown)))
    extract(args)
    args.locales, args.verbose, args.strict = [], False, False
    check(args)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--upstream', help='a herdr-app source tree to use instead of the pinned release')
    commands = parser.add_subparsers(dest='command', required=True)
    commands.add_parser('fetch')
    commands.add_parser('extract')
    p = commands.add_parser('new')
    p.add_argument('locale')
    p.add_argument('--name', required=True, help='the language in itself, e.g. 日本語')
    p.add_argument('--title', required=True, help='the layout name people pick, e.g. "Herdr 日本語"')
    p = commands.add_parser('check')
    p.add_argument('locales', nargs='*')
    p.add_argument('-v', '--verbose', action='store_true', help='list every missing and stale text')
    p.add_argument('--strict', action='store_true', help='fail on missing or stale texts too')
    p = commands.add_parser('build')
    p.add_argument('locales', nargs='*')
    p = commands.add_parser('install')
    p.add_argument('locale')
    p.add_argument('--home', help='the Herdr app home (default: $HERDR_APP_HOME or ~/.config/herdr-app)')
    p.add_argument('--keys', action='store_true', help="also point this layout's shortcuts at the translated screens")
    p = commands.add_parser('upgrade')
    p.add_argument('tag')
    args = parser.parse_args()
    if args.command == 'fetch':
        upstream(args)
    else:
        {'extract': extract, 'new': new, 'check': check, 'build': build,
         'install': install, 'upgrade': upgrade}[args.command](args)


if __name__ == '__main__':
    main()
